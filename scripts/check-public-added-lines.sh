#!/usr/bin/env bash
set -euo pipefail

repo_root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
cd "$repo_root"

base=${1:-}
if [[ -z "$base" ]]; then
  added=$(
    # Binding documentation is generated from the Rust sources, which are scanned directly.
    git diff --unified=0 HEAD -- . ':!Cargo.lock' ':!beebeeb-uniffi/bindings/**' ':!bindings/kotlin/**' \
      | sed -n '/^+++ /d; /^+/s/^+//p'
    while IFS= read -r path; do
      if [[ "$path" == Cargo.lock || "$path" == beebeeb-uniffi/bindings/* || "$path" == bindings/kotlin/* ]]; then
        continue
      fi
      sed -n 'p' "$path"
    done < <(git ls-files --others --exclude-standard)
  )
else
  if [[ "$base" =~ ^0+$ ]]; then
    base=HEAD^
  fi
  if ! git rev-parse --verify "$base^{commit}" >/dev/null 2>&1; then
    echo "cannot resolve diff base: $base" >&2
    exit 1
  fi
  added=$(
    # Binding documentation is generated from the Rust sources, which are scanned directly.
    git diff --unified=0 "$base"...HEAD -- . ':!Cargo.lock' ':!beebeeb-uniffi/bindings/**' ':!bindings/kotlin/**' \
      | sed -n '/^+++ /d; /^+/s/^+//p'
  )
fi

internal_a='ta'
internal_b='sk'
tick='`'
private_terms="${internal_a}${internal_b}[[:space:]]+[#-]?[0-9]|la"'ne|roll'"out|orches"'trator|dis'"patch|\\.super"'powers|core #[0-9]|bra'"nch ${tick}[^${tick}]+${tick}"
actor_a='ag'
actor_b='ent'
helper_a='assi'
helper_b='stant'
automation_a='b'
automation_b='ot'
attribution_terms="coding (${actor_a}${actor_b}|${helper_a}${helper_b})|generated by (an )?(${actor_a}${actor_b}|${helper_a}${helper_b})|co-authored-by:.*(${automation_a}${automation_b}|${actor_a}${actor_b})"

if grep -Ein "(^|[^[:alnum:]_])(${private_terms})([^[:alnum:]_]|$)" <<< "$added"; then
  echo 'added lines contain an internal work reference' >&2
  exit 1
fi
if grep -Ein "$attribution_terms" <<< "$added"; then
  echo 'added lines contain tool attribution' >&2
  exit 1
fi

echo 'public added-line guard passed'
