#!/usr/bin/env python3
"""Write core's simple case-folding table from the Unicode data file.

Usage:
    python3 -I test-vectors/tools/gen_case_fold_table.py beebeeb-core/src/name_tag/case_fold.rs

The table is the C and S rows of CaseFolding.txt (simple folding; never F, never T), at the Unicode
version `unicode-normalization` pins in Cargo.lock, so that NFKC and folding come from one version.
`scripts/check-test-vectors.sh` regenerates it and fails when the committed file differs.
"""
from pathlib import Path
import sys

UCD = Path(__file__).parent / "ucd" / "CaseFolding-17.0.0.txt"
VERSION = "17.0.0"
PER_LINE = 5


def simple_folds(path):
    rows = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        code, status, mapping = [field.strip() for field in line.split(";")[:3]]
        if status not in ("C", "S"):
            continue
        target = mapping.split()
        assert len(target) == 1, line
        rows.append((int(code, 16), int(target[0], 16)))
    rows.sort()
    assert len({code for code, _ in rows}) == len(rows), "a code point folds twice"
    return rows


def main():
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("beebeeb-core/src/name_tag/case_fold.rs")
    rows = simple_folds(UCD)
    head = [
        f"//! Simple case folding (CaseFolding.txt statuses C and S), Unicode {VERSION}.",
        "//!",
        "//! Generated by `test-vectors/tools/gen_case_fold_table.py` from",
        f"//! `test-vectors/tools/ucd/CaseFolding-{VERSION}.txt`; never edit it by hand",
        "//! (`scripts/check-test-vectors.sh` fails on a difference).",
        "",
        f'pub(super) const UNICODE_VERSION: &str = "{VERSION}";',
        "",
        "/// `(code point, simple case fold)`, sorted by code point.",
        "#[rustfmt::skip]",
        f"pub(super) const SIMPLE_FOLDS: [(u32, u32); {len(rows)}] = [",
    ]
    body = []
    for start in range(0, len(rows), PER_LINE):
        chunk = rows[start:start + PER_LINE]
        body.append("    " + " ".join(f"(0x{a:05X}, 0x{b:05X})," for a, b in chunk))
    out.write_text("\n".join(head + body + ["];", ""]), encoding="utf-8")


if __name__ == "__main__":
    main()
