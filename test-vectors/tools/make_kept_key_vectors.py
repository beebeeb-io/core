#!/usr/bin/env python3
"""Generate test-vectors/kept_key.json: the kept-key acceptance rule (beebeeb-client auth::kept_key).

Each row's expected answer is written by hand from the desktop's rule (repos/desktop
crates/beebeeb-engine/src/app/kept_key_proof.rs read_kept_key, signin/key_owner.rs tag_is_account,
account_binding.rs same_email, signin/recovery.rs recovery_check_answer), and checked here against an
independent Python port of that rule, never against the Rust it tests:

- the owner tag is read as UTF-8; a tag that is not UTF-8 cannot be read: NoneHere;
- a tag that is blank after trimming counts as no tag;
- a tag decides alone: ProveIt only when tag.trim() == signing_user_id.trim() and that is not blank;
- with no tag: ProveIt only when canonical_email(stored) is not empty and equals canonical_email(signing);
  canonical_email is trim, then Unicode lowercase; no stored email: NoneHere;
- a proof answer counts only on HTTP 400 with the exact code `recovery_check_missing` (NoCheckOnFile) or
  `invalid_recovery_phrase` (WrongPhrase); every other status or code is Unavailable.

Rows are added HERE, never in the JSON: scripts/check-test-vectors.sh fails on a hand edit.

    python3 -I test-vectors/tools/make_kept_key_vectors.py test-vectors/kept_key.json
"""
import json
import sys

DESCRIPTION = (
    "Kept-key acceptance rule (beebeeb-client auth::kept_key). Generated by "
    "test-vectors/tools/make_kept_key_vectors.py; do not edit by hand. owner_tag_hex is the owner tag "
    "bytes in hex (the owning user id as UTF-8); null means no tag. Emails compare under canonical_email: "
    "trim, then Unicode lowercase."
)

U1 = "usr-1".encode().hex()
U2 = "usr-2".encode().hex()

# (name, owner_tag_hex, stored_email, signing_user_id, signing_email, expect)
USE_ROWS = [
    ("owner tag matches", U1, "a@example.eu", "usr-1", "a@example.eu", "ProveIt"),
    ("owner tag matches, stored email differs (tag wins)", U1, "old@example.eu", "usr-1", "a@example.eu", "ProveIt"),
    ("owner tag matches, no stored email", U1, None, "usr-1", "a@example.eu", "ProveIt"),
    ("owner tag matches after trimming both", " usr-1 ".encode().hex(), None, "usr-1\n", "a@example.eu", "ProveIt"),
    ("foreign tag, same email (tag wins)", U2, "a@example.eu", "usr-1", "a@example.eu", "NoneHere"),
    ("foreign tag, prefix of signing id", "usr-".encode().hex(), "a@example.eu", "usr-1", "a@example.eu", "NoneHere"),
    ("foreign tag, differs only in case", "USR-1".encode().hex(), "a@example.eu", "usr-1", "a@example.eu", "NoneHere"),
    ("unreadable tag (not UTF-8), same email", "ff00fe", "a@example.eu", "usr-1", "a@example.eu", "NoneHere"),
    ("tag present, blank signing id", U1, "a@example.eu", " ", "a@example.eu", "NoneHere"),
    ("blank tag, no email, blank signing id (refuse)", "20", None, " ", "a@example.eu", "NoneHere"),
    ("blank tag, same email (falls to the email rule)", "20", "a@example.eu", "usr-1", "a@example.eu", "ProveIt"),
    ("blank tag, blank signing id, same email", "20", "a@example.eu", " ", "a@example.eu", "ProveIt"),
    ("blank tag, other email", "2009", "b@example.eu", "usr-1", "a@example.eu", "NoneHere"),
    ("empty tag, same email (falls to the email rule)", "", "a@example.eu", "usr-1", "a@example.eu", "ProveIt"),
    ("untagged, same email", None, "a@example.eu", "usr-1", "a@example.eu", "ProveIt"),
    ("untagged, same email under canonical_email", None, "  A@Example.EU ", "usr-1", "a@example.eu", "ProveIt"),
    ("untagged, same email under Unicode lowercase", None, "ÉLISE@example.eu", "usr-1", "élise@example.eu", "ProveIt"),
    ("untagged, other email", None, "b@example.eu", "usr-1", "a@example.eu", "NoneHere"),
    ("untagged, provider rewriting is not applied", None, "a.b@example.eu", "usr-1", "ab@example.eu", "NoneHere"),
    ("untagged, no stored email", None, None, "usr-1", "a@example.eu", "NoneHere"),
    ("untagged, blank stored email", None, "  ", "usr-1", "", "NoneHere"),
]

# (answer, status, error_code, expect, tag_it). status/error_code null: the answer is given directly (a 2xx match).
VERDICT_ROWS = [
    ("Matched", None, None, "Proven", True),
    ("NoCheckOnFile", 400, "recovery_check_missing", "Proven", False),
    ("WrongPhrase", 400, "invalid_recovery_phrase", "Outdated", None),
    ("Unavailable", 400, "rate_limited", "Unavailable", None),
    ("Unavailable", 400, "", "Unavailable", None),
    ("Unavailable", 400, "Invalid_Recovery_Phrase", "Unavailable", None),
    ("Unavailable", 422, "invalid_recovery_phrase", "Unavailable", None),
    ("Unavailable", 409, "recovery_check_missing", "Unavailable", None),
    ("Unavailable", 500, "invalid_recovery_phrase", "Unavailable", None),
    ("Unavailable", 200, "invalid_recovery_phrase", "Unavailable", None),
    ("Unavailable", None, None, "Unavailable", None),
]

SEQ = bytes(range(32)).hex()
SAME_ROWS = [
    ("", ""),
    (SEQ, SEQ),
    (SEQ, SEQ[:-2] + "1e"),
    ("80" + SEQ[2:], SEQ),
    (SEQ, SEQ[:-2]),
    ("00", ""),
]


def canonical_email(s):
    return s.strip().lower()


def port_use(tag_hex, stored, signing_id, signing_email):
    if tag_hex is not None:
        try:
            tag = bytes.fromhex(tag_hex).decode("utf-8")
        except UnicodeDecodeError:
            return "NoneHere"
        if tag.strip():
            ok = tag.strip() == signing_id.strip() and signing_id.strip() != ""
            return "ProveIt" if ok else "NoneHere"
    if stored is None:
        return "NoneHere"
    s = canonical_email(stored)
    return "ProveIt" if s and s == canonical_email(signing_email) else "NoneHere"


def port_answer(status, code):
    if status != 400:
        return "Unavailable"
    return {"recovery_check_missing": "NoCheckOnFile", "invalid_recovery_phrase": "WrongPhrase"}.get(code, "Unavailable")


def port_verdict(answer):
    return {
        "Matched": ("Proven", True),
        "NoCheckOnFile": ("Proven", False),
        "WrongPhrase": ("Outdated", None),
        "Unavailable": ("Unavailable", None),
    }[answer]


def build():
    use = []
    for name, tag, stored, sid, semail, expect in USE_ROWS:
        got = port_use(tag, stored, sid, semail)
        assert got == expect, f"{name}: port says {got}, row says {expect}"
        use.append({
            "name": name,
            "owner_tag_hex": tag,
            "stored_email": stored,
            "signing_user_id": sid,
            "signing_email": semail,
            "expect": expect,
        })
    verdict = []
    for answer, status, code, expect, tag_it in VERDICT_ROWS:
        if status is not None:
            got = port_answer(status, code)
            assert got == answer, f"{status} {code!r}: port says {got}, row says {answer}"
        assert port_verdict(answer) == (expect, tag_it), answer
        verdict.append({"answer": answer, "status": status, "error_code": code, "expect": expect, "tag_it": tag_it})
    same = [{"a_hex": a, "b_hex": b, "expect": a == b} for a, b in SAME_ROWS]
    return {"description": DESCRIPTION, "may_use_kept_key": use, "verdict": verdict, "same_key": same}


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: make_kept_key_vectors.py OUT.json")
    text = json.dumps(build(), indent=2, ensure_ascii=False) + "\n"
    with open(sys.argv[1], "w", encoding="utf-8", newline="") as f:
        f.write(text)


if __name__ == "__main__":
    main()
